import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('saved quotes, delivery and simulated fulfilment enforce ownership, immutable totals and ordered transitions', async()=>{
  const db=new PGlite();
  const alice='00000000-0000-4000-8000-000000000001', bob='00000000-0000-4000-8000-000000000002', admin='00000000-0000-4000-8000-000000000003';
  const id='10000000-0000-4000-8000-000000000001', second='10000000-0000-4000-8000-000000000002';
  const item={title:'Chemise',variant:'M',quantity:2,shop:'shein',url:'https://fr.shein.com/example.html',note:''};
  const session=async(role,user='')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);await db.exec(`set role ${role}`);};
  const decide=(request,version,accept)=>db.query('select public.jibli_decide_quote($1,$2,$3) as status',[request,version,accept]);
  const delivery=(request=id,version=2,revision=0,address='12 rue Exemple, bâtiment A',city='Tunis',postcode='1000')=>db.query('select public.jibli_save_delivery($1,$2,$3,$4,$5,$6) as revision',[request,version,revision,address,city,postcode]);
  try {
    await db.exec(`create role anon nologin; create role authenticated nologin; create schema auth;
    create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid; $$;
    grant usage on schema auth,public to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;`);
    for(const [user,email] of [[alice,'alice@example.com'],[bob,'bob@example.com'],[admin,'admin@example.com']])await db.query('insert into auth.users values($1,$2,now())',[user,email]);
    for(const file of ['202611110001_accounts_requests.sql','202611110002_quotes.sql','202611110003_delivery_details.sql','202611110004_simulated_fulfilment.sql'])await db.exec(await readFile(new URL('../supabase/migrations/'+file,import.meta.url),'utf8'));
    await db.query('insert into public.jibli_admins values($1)',[admin]);
    await session('authenticated',alice);
    for(const request of [id,second])await db.query('select public.jibli_create_request($1,$2,$3,$4,$5::jsonb)',[request,'Client test','20202020','Tunis',JSON.stringify([item])]);
    await assert.rejects(delivery(),/Acceptez le devis/,'delivery cannot be saved before acceptance');
    const itemId=(await db.query('select id from public.jibli_request_items where request_id=$1',[id])).rows[0].id;
    const secondItem=(await db.query('select id from public.jibli_request_items where request_id=$1',[second])).rows[0].id;
    const prices={[itemId]:30125};const costs={transport:10000,customs:3000,service:5000,delivery:7000};
    const publish=(expected,overrides={})=>db.query('select public.jibli_publish_quote($1,$2,$3::jsonb,$4::jsonb,$5,$6,$7,$8) as version',[
      overrides.id??id,expected,JSON.stringify(overrides.prices??prices),JSON.stringify(overrides.costs??costs),overrides.days??7,overrides.min??12,overrides.max??18,overrides.note??'Test']);
    await assert.rejects(publish(0),/administrateur/);
    await session('anon');
    await assert.rejects(publish(0),/permission denied/);
    await assert.rejects(db.query('select * from public.jibli_quotes'),/permission denied/);
    await assert.rejects(decide(id,1,true),/permission denied/);
    await assert.rejects(delivery(),/permission denied/);
    await assert.rejects(db.query('select * from public.jibli_deliveries'),/permission denied/);
    await session('authenticated',admin);
    for(const invalid of [{prices:{}},{prices:{...prices,extra:1}},{prices:{[itemId]:0}},{prices:{[itemId]:1.5}},{prices:{[itemId]:'30125'}},{costs:{...costs,extra:1}},{costs:{...costs,customs:-1}},{min:20,max:10},{days:31},{note:'x'.repeat(1001)}])await assert.rejects(publish(0,invalid));
    assert.equal((await db.query('select count(*) as n from public.jibli_quotes')).rows[0].n,0,'failed drafts leave no quote');
    assert.equal((await publish(0)).rows[0].version,1);
    const first=(await db.query('select * from public.jibli_quotes where request_id=$1',[id])).rows[0];
    assert.equal(Number(first.total),85250,'database computes quantity × price + every fee');
    await assert.rejects(publish(0),/Version modifiée/);
    assert.equal((await publish(1,{prices:{[itemId]:40125}})).rows[0].version,2);
    const savedFirst=(await db.query('select * from public.jibli_quotes where request_id=$1 and version=1',[id])).rows[0];
    assert.deepEqual(savedFirst,first,'revision preserves the complete previous quote');
    await assert.rejects(db.exec('update public.jibli_quotes set total=1'),/permission denied/);
    await assert.rejects(db.exec('delete from public.jibli_quotes'),/permission denied/);
    await assert.rejects(decide(id,2,true),/Accès refusé/,'admin cannot impersonate the customer');
    await session('authenticated',bob);
    assert.equal((await db.query('select count(*) as n from public.jibli_quotes')).rows[0].n,0);
    await assert.rejects(decide(id,2,true),/Accès refusé/);
    await session('authenticated',alice);
    assert.equal((await db.query('select count(*) as n from public.jibli_quotes')).rows[0].n,2);
    await assert.rejects(decide(id,1,true),/Version modifiée/);
    assert.equal((await decide(id,2,true)).rows[0].status,'awaiting_payment');
    assert.equal((await db.query('select accepted_version from public.jibli_requests where id=$1',[id])).rows[0].accepted_version,2);
    await assert.rejects(decide(id,2,false),/Version modifiée/);
    await session('authenticated',admin);
    await assert.rejects(publish(2),/verrouillé/);
    await publish(0,{id:second,prices:{[secondItem]:30125}});
    await session('postgres');
    await db.query("update public.jibli_quotes set valid_until=clock_timestamp()-interval '1 second' where request_id=$1",[second]);
    await session('authenticated',alice);
    await assert.rejects(decide(second,1,true),/expiré/);
    await assert.rejects(decide(second,1,false),/expiré/);
    await session('authenticated',admin);
    await publish(1,{id:second,prices:{[secondItem]:30125}});
    await session('authenticated',alice);
    assert.equal((await decide(second,2,false)).rows[0].status,'declined');
    await assert.rejects(delivery(second),/Acceptez le devis/,'declined request cannot save delivery');
    await assert.rejects(delivery(id,1),/Acceptez le devis/,'delivery belongs to accepted quote version');
    for (const [address,city,postcode] of [['short','Tunis','1000'],['x'.repeat(501),'Tunis','1000'],['12 rue Exemple','Sfax','1000'],['12 rue Exemple','Tunis','abc'],['12 rue Exemple','Tunis','12345']]) await assert.rejects(delivery(id,2,0,address,city,postcode));
    assert.equal((await db.query('select count(*) as n from public.jibli_delivery_events')).rows[0].n,0,'invalid delivery does not create history');
    assert.equal((await delivery()).rows[0].revision,1);
    const acceptedQuote=(await db.query('select * from public.jibli_quotes where request_id=$1 and version=2',[id])).rows[0];
    assert.equal((await delivery(id,2,1)).rows[0].revision,1,'identical save does not duplicate history');
    await assert.rejects(delivery(id,2,0,'24 rue Exemple, bâtiment B'),/coordonnées ont changé/,'stale edit cannot overwrite current address');
    assert.equal((await delivery(id,2,1,'24 rue Exemple, bâtiment B')).rows[0].revision,2);
    assert.equal((await db.query('select count(*) as n from public.jibli_delivery_events')).rows[0].n,2);
    const savedDelivery=(await db.query('select * from public.jibli_deliveries')).rows[0];
    assert.equal(savedDelivery.address,'24 rue Exemple, bâtiment B');
    await assert.rejects(db.exec("update public.jibli_deliveries set city='Sfax'"),/permission denied/);
    await assert.rejects(db.exec('delete from public.jibli_delivery_events'),/permission denied/);
    await assert.rejects(db.exec('insert into public.jibli_deliveries default values'),/permission denied/);
    await session('authenticated',bob);
    assert.equal((await db.query('select count(*) as n from public.jibli_deliveries')).rows[0].n,0,'foreign address is private');
    assert.equal((await db.query('select count(*) as n from public.jibli_delivery_events')).rows[0].n,0,'foreign history is private');
    await assert.rejects(delivery(id,2,2),/Accès refusé/);
    await session('authenticated',admin);
    assert.equal((await db.query('select * from public.jibli_deliveries')).rows[0].address,savedDelivery.address,'admin can read delivery');
    await assert.rejects(delivery(id,2,2),/Accès refusé/,'admin cannot silently replace customer address');
    assert.deepEqual((await db.query('select * from public.jibli_quotes where request_id=$1 and version=2',[id])).rows[0],acceptedQuote,'delivery updates preserve accepted prices');
    assert.equal((await db.query('select status from public.jibli_requests where id=$1',[id])).rows[0].status,'awaiting_payment','address does not confirm payment or shipment');
    await assert.rejects(publish(2,{id:second,prices:{[secondItem]:30125}}),/verrouillé/);
    const declare=(request=id,version=2,revision=2)=>db.query('select public.jibli_declare_simulation($1,$2,$3) as status',[request,version,revision]);
    const advance=(expected,tracking='')=>db.query('select public.jibli_advance_simulation($1,$2,$3) as status',[id,expected,tracking]);
    await assert.rejects(advance('awaiting_payment'),/Simulation de paiement requise/);
    await assert.rejects(declare(),/Accès refusé/,'admin cannot declare payment for a customer');
    await session('anon');
    await assert.rejects(declare(),/permission denied/);
    await assert.rejects(advance('payment_review'),/permission denied/);
    await assert.rejects(db.query('select * from public.jibli_simulations'),/permission denied/);
    await session('authenticated',bob);
    await assert.rejects(declare(),/Accès refusé/);
    await session('authenticated',alice);
    await assert.rejects(declare(second),/Devis accepté requis/,'declined quote cannot simulate a payment');
    await assert.rejects(declare(id,1),/Devis accepté requis/);
    await assert.rejects(declare(id,2,1),/Livraison absente ou modifiée/);
    assert.equal((await declare()).rows[0].status,'payment_review');
    assert.equal((await declare()).rows[0].status,'payment_review','retry cannot duplicate payment simulation');
    const simulation=(await db.query('select * from public.jibli_simulations')).rows[0];
    assert.equal(simulation.simulation,true);
    assert.match(simulation.reference,/^TEST-/);
    assert.equal(Number(simulation.amount),Number(acceptedQuote.total),'simulation uses exact accepted quote amount');
    assert.equal(simulation.confirmed_at,null,'customer declaration is not admin confirmation');
    assert.equal((await db.query('select count(*) as n from public.jibli_simulations')).rows[0].n,1);
    await assert.rejects(delivery(id,2,2,'35 rue Exemple'),/Acceptez le devis/,'address locks when simulation begins');
    await assert.rejects(advance('payment_review'),/administrateur/);
    await assert.rejects(db.exec('update public.jibli_simulations set amount=1'),/permission denied/);
    await assert.rejects(db.exec('delete from public.jibli_simulation_events'),/permission denied/);
    await session('authenticated',bob);
    assert.equal((await db.query('select count(*) as n from public.jibli_simulations')).rows[0].n,0);
    assert.equal((await db.query('select count(*) as n from public.jibli_simulation_events')).rows[0].n,0);
    await session('authenticated',admin);
    await assert.rejects(advance('ordered','DEMO-001'),/Étape modifiée/,'cannot skip payment confirmation');
    assert.equal((await advance('payment_review')).rows[0].status,'ordered');
    assert.ok((await db.query('select confirmed_at from public.jibli_simulations')).rows[0].confirmed_at);
    await assert.rejects(advance('payment_review'),/Étape modifiée/,'repeated admin action cannot advance twice');
    await assert.rejects(advance('ordered'),/référence fictive/);
    await assert.rejects(advance('ordered','REAL-CARRIER-001'),/référence fictive/);
    assert.equal((await advance('ordered','DEMO-TRACK-001')).rows[0].status,'in_transit');
    assert.equal((await advance('in_transit')).rows[0].status,'delivered');
    await assert.rejects(advance('delivered'),/Étape indisponible/);
    assert.equal((await db.query('select count(*) as n from public.jibli_simulation_events')).rows[0].n,4,'each stage has one persisted simulation event');
    assert.equal((await db.query('select tracking from public.jibli_simulations')).rows[0].tracking,'DEMO-TRACK-001');
    assert.deepEqual((await db.query('select * from public.jibli_quotes where request_id=$1 and version=2',[id])).rows[0],acceptedQuote,'simulated fulfilment never changes the accepted quote');
    await session('authenticated',alice);
    assert.equal((await declare()).rows[0].status,'delivered','late retry does not rewind completed simulation');
    await session('postgres');await db.query('delete from public.jibli_admins where user_id=$1',[admin]);
    await session('authenticated',admin);
    await assert.rejects(publish(2),/administrateur/);
  } finally {await db.close();}
});
